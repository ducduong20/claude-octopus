#!/usr/bin/env python3
"""Turns the sprite sheets in media/sprites into Sprites.swift (frames as character grids).

Run from the repository root after changing a sheet:  python3 -I native/macos/make_sprites.py
The sheet has one row per animation and 22 x 22 frames.
Colours map to letters: B body, E eyes, L light prop, K dark, C blue, R red; anything transparent
is '.'.
"""
import os
import struct
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SHEET = os.path.join(ROOT, 'media', 'sprites', 'octopus.png')
OUT = os.path.join(ROOT, 'native', 'macos', 'Sprites.swift')

# (name, frames, fps, loops) in sheet row order.
ANIMS = [
    ('idle', 6, 3, True), ('walk', 4, 6, True), ('eating', 6, 6, False), ('football', 6, 6, True),
    ('music', 4, 4, True), ('chill', 4, 2, True), ('lift', 6, 4, True), ('working', 4, 6, True),
    ('coffee', 6, 4, True), ('vibe', 4, 4, True), ('tired', 4, 2, True), ('tired_walk', 4, 3, True),
    ('nearly_out', 6, 2, True), ('hibernate', 6, 2, True), ('sleep', 4, 2, True), ('stretch', 6, 4, False),
]
LETTERS = {(0xd9, 0x77, 0x57): 'B', (0xff, 0xff, 0xff): 'E', (0x2b, 0x1b, 0x14): 'E',
           (0xe6, 0xe8, 0xec): 'L', (0xa3, 0xa8, 0xb2): 'L', (0x1a, 0x1a, 0x1a): 'K',
           (0x5a, 0xb0, 0xf0): 'C', (0xe5, 0x53, 0x4b): 'R'}
CELL = 22


def decode_png(path):
    """Minimal decoder for 8-bit, non-interlaced RGB, RGBA or palette PNGs."""
    data = open(path, 'rb').read()
    pos, idat, plte, trns = 8, b'', None, None
    while pos < len(data):
        n, = struct.unpack('>I', data[pos:pos + 4])
        kind, body = data[pos + 4:pos + 8], data[pos + 8:pos + 8 + n]
        pos += 12 + n
        if kind == b'IHDR':
            w, h, depth, ctype = struct.unpack('>IIBB', body[:10])
            if depth != 8 or body[12] != 0:
                sys.exit(f'{path}: only 8-bit, non-interlaced PNGs are supported')
        elif kind == b'IDAT':
            idat += body
        elif kind == b'PLTE':
            plte = body
        elif kind == b'tRNS':
            trns = body
    raw = zlib.decompress(idat)
    bpp = {6: 4, 2: 3, 3: 1}[ctype]
    stride, prev, rows, i = w * bpp, bytearray(w * bpp), [], 0
    for _ in range(h):
        f, line = raw[i], bytearray(raw[i + 1:i + 1 + stride])
        i += 1 + stride
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if f == 1:
                line[x] = (line[x] + a) & 255
            elif f == 2:
                line[x] = (line[x] + b) & 255
            elif f == 3:
                line[x] = (line[x] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(bytes(line))
        prev = line
    px = []
    for r in rows:
        out = []
        for x in range(w):
            if ctype == 6:
                out.append(tuple(r[x * 4:x * 4 + 4]))
            elif ctype == 2:
                out.append(tuple(r[x * 3:x * 3 + 3]) + (255,))
            else:
                k = r[x]
                alpha = trns[k] if trns and k < len(trns) else 255
                out.append(tuple(plte[k * 3:k * 3 + 3]) + (alpha,))
        px.append(out)
    return w, h, px


def grid(px, x0, y0, w, h):
    rows = []
    for y in range(y0, y0 + h):
        row = ''
        for x in range(x0, x0 + w):
            p = px[y][x]
            if p[3] < 128:
                row += '.'
            elif p[:3] in LETTERS:
                row += LETTERS[p[:3]]
            else:
                sys.exit(f'unexpected colour #{p[0]:02x}{p[1]:02x}{p[2]:02x} at {x},{y}')
        rows.append(row)
    return ''.join(rows)


def main():
    w, h, px = decode_png(SHEET)
    if (w, h) != (CELL * 6, CELL * len(ANIMS)):
        sys.exit(f'{SHEET}: expected {CELL * 6} x {CELL * len(ANIMS)}, got {w} x {h}')
    out = ['// Generated by native/macos/make_sprites.py from media/sprites. Do not edit by hand.',
           '// Each frame is 22 x 22 characters, row by row: "." transparent, B body, E eyes, L light prop,',
           '// K dark, C blue, R red.',
           '', 'struct Anim {', '    let fps: Double', '    let loops: Bool', '    let frames: [String]', '}', '',
           'enum Sprites {', '    static let size = 22', '', '    static let anims: [String: Anim] = [']
    for row, (name, n, fps, loops) in enumerate(ANIMS):
        out.append(f'        "{name}": Anim(fps: {fps}, loops: {"true" if loops else "false"}, frames: [')
        for f in range(n):
            out.append(f'            "{grid(px, f * CELL, row * CELL, CELL, CELL)}",')
        out.append('        ]),')
    out += ['    ]', '}', '']
    open(OUT, 'w').write('\n'.join(out))
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
